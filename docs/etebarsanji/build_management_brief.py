def _rpr_fonts(rPr, name):
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:cs"), name)
    rFonts.set(qn("w:eastAsia"), name)


def set_run(run, text, *, font=BODY_FONT, size=12, bold=False, color=DARK, italic=False):
    run.text = text
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.color.rgb = color
    run.font.name = font
    rPr = run._r.get_or_add_rPr()
    _rpr_fonts(rPr, font)
    rtl = rPr.find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        rPr.append(rtl)
    cs = rPr.find(qn("w:cs"))
    if cs is None:
        cs = OxmlElement("w:cs")
        rPr.append(cs)


def set_paragraph_rtl(p, *, align="right", space_after=8, space_before=0, line=1.15):
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.line_spacing = line
    if align == "right":
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    elif align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "left":
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    elif align == "justify":
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pPr = p._p.get_or_add_pPr()
    bidi = pPr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        pPr.append(bidi)
    bidi.set(qn("w:val"), "1")
    jc = pPr.find(qn("w:jc"))
    if jc is None:
        jc = OxmlElement("w:jc")
        pPr.append(jc)
    jc_map = {
        "right": "right",
        "center": "center",
        "left": "left",
        "justify": "both",
    }
    jc.set(qn("w:val"), jc_map[align])


def add_p(doc, text, *, size=12, bold=False, color=DARK, align="justify",
          space_after=8, space_before=0, font=BODY_FONT, first_line=None):
    p = doc.add_paragraph()
    set_paragraph_rtl(p, align=align, space_after=space_after, space_before=space_before)
    if first_line is not None:
        p.paragraph_format.first_line_indent = Cm(first_line)
    run = p.add_run()
    set_run(run, text, font=font, size=size, bold=bold, color=color)
    return p


def add_heading_custom(doc, text, level=1):
    p = doc.add_paragraph()
    sizes = {0: 22, 1: 16, 2: 13.5, 3: 12}
    after = {0: 10, 1: 10, 2: 8, 3: 6}
    before = {0: 0, 1: 16, 2: 12, 3: 8}
    align = "center" if level == 0 else "right"
    set_paragraph_rtl(p, align=align, space_after=after[level], space_before=before[level], line=1.2)
    run = p.add_run()
    color = NAVY if level <= 1 else TEAL
    set_run(run, text, font=HEAD_FONT, size=sizes[level], bold=True, color=color)
    if level in (0, 1):
        pPr = p._p.get_or_add_pPr()
        pBdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "12" if level == 0 else "8")
        bottom.set(qn("w:space"), "4")
        bottom.set(qn("w:color"), "B88A2E" if level == 0 else "1B365D")
        pBdr.append(bottom)
        pPr.append(pBdr)
    return p


def shade_cell(cell, hex_color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = tcPr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tcPr.append(shd)
    shd.set(qn("w:fill"), hex_color)
    shd.set(qn("w:val"), "clear")


def set_cell_border(cell, **kwargs):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = tcPr.find(qn("w:tcBorders"))
    if tcBorders is None:
        tcBorders = OxmlElement("w:tcBorders")
        tcPr.append(tcBorders)
    for edge, val in kwargs.items():
        el = tcBorders.find(qn(f"w:{edge}"))
        if el is None:
            el = OxmlElement(f"w:{edge}")
            tcBorders.append(el)
        el.set(qn("w:val"), val.get("val", "single"))
        el.set(qn("w:sz"), val.get("sz", "4"))
        el.set(qn("w:color"), val.get("color", "1B365D"))
        el.set(qn("w:space"), "0")


def set_cell_text(cell, text, *, bold=False, size=10.5, color=DARK, align="right",
                  font=BODY_FONT, fill=None):
    cell.text = ""
    p = cell.paragraphs[0]
    set_paragraph_rtl(p, align=align, space_after=2, space_before=2, line=1.1)
    run = p.add_run()
    set_run(run, text, font=font, size=size, bold=bold, color=color)
    if fill:
        shade_cell(cell, fill)
    set_cell_border(
        cell,
        top={"sz": "4", "color": "C5CDD8"},
        bottom={"sz": "4", "color": "C5CDD8"},
        start={"sz": "4", "color": "C5CDD8"},
        end={"sz": "4", "color": "C5CDD8"},
    )
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    vAlign = tcPr.find(qn("w:vAlign"))
    if vAlign is None:
        vAlign = OxmlElement("w:vAlign")
        tcPr.append(vAlign)
    vAlign.set(qn("w:val"), "center")


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    tbl = table._tbl
    tblPr = tbl.tblPr if tbl.tblPr is not None else OxmlElement("w:tblPr")
    bidi = OxmlElement("w:bidiVisual")
    bidi.set(qn("w:val"), "1")
    tblPr.append(bidi)
    jc = OxmlElement("w:jc")
    jc.set(qn("w:val"), "center")
    tblPr.append(jc)
    for i, h in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], h, bold=True, size=10.5, color=WHITE,
                      align="center", font=HEAD_FONT, fill=HEADER_BG)
    for r_i, row in enumerate(rows):
        fill = ROW_ALT if r_i % 2 else "FFFFFF"
        for c_i, val in enumerate(row):
            set_cell_text(table.rows[r_i + 1].cells[c_i], val, size=10.5, fill=fill)
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return table


def add_callout(doc, title, body, fill=GOLD_BG):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.rows[0].cells[0]
    shade_cell(cell, fill)
    set_cell_border(
        cell,
        top={"sz": "12", "color": "B88A2E"},
        bottom={"sz": "4", "color": "B88A2E"},
        start={"sz": "12", "color": "B88A2E"},
        end={"sz": "4", "color": "B88A2E"},
    )
    cell.text = ""
    p1 = cell.paragraphs[0]
    set_paragraph_rtl(p1, align="right", space_after=4, space_before=4)
    r1 = p1.add_run()
    set_run(r1, title, font=HEAD_FONT, size=12, bold=True, color=NAVY)
    p2 = cell.add_paragraph()
    set_paragraph_rtl(p2, align="justify", space_after=4, space_before=0)
    r2 = p2.add_run()
    set_run(r2, body, font=BODY_FONT, size=11.5, color=DARK)
    doc.add_paragraph()


def add_bullet(doc, text, *, bold_prefix=None):
    p = doc.add_paragraph()
    set_paragraph_rtl(p, align="justify", space_after=4, space_before=1)
    p.paragraph_format.right_indent = Cm(0)
    p.paragraph_format.left_indent = Cm(0.4)
    if bold_prefix:
        r0 = p.add_run()
        set_run(r0, "•  " + bold_prefix, font=BODY_FONT, size=12, bold=True, color=NAVY)
        r1 = p.add_run()
        set_run(r1, text, font=BODY_FONT, size=12, color=DARK)
    else:
        r = p.add_run()
        set_run(r, "•  " + text, font=BODY_FONT, size=12, color=DARK)
    return p


def add_page_number(paragraph):
    def _fld(instr):
        r1 = paragraph.add_run()
        fc1 = OxmlElement("w:fldChar")
        fc1.set(qn("w:fldCharType"), "begin")
        r1._r.append(fc1)
        r2 = paragraph.add_run()
        it = OxmlElement("w:instrText")
        it.set(qn("xml:space"), "preserve")
        it.text = instr
        r2._r.append(it)
        r3 = paragraph.add_run()
        fc2 = OxmlElement("w:fldChar")
        fc2.set(qn("w:fldCharType"), "end")
        r3._r.append(fc2)
        for run in (r1, r2, r3):
            set_run(run, run.text or "", font=BODY_FONT, size=9, color=GRAY)

    pre = paragraph.add_run()
    set_run(pre, "صفحه ", font=BODY_FONT, size=9, color=GRAY)
    _fld(" PAGE ")
    mid = paragraph.add_run()
    set_run(mid, " از ", font=BODY_FONT, size=9, color=GRAY)
    _fld(" NUMPAGES ")


def setup_doc():
    doc = Document()
    for section in doc.sections:
        section.page_width = Cm(21.0)
        section.page_height = Cm(29.7)
        section.top_margin = Cm(2.2)
        section.bottom_margin = Cm(2.2)
        section.right_margin = Cm(2.3)
        section.left_margin = Cm(2.0)
        sectPr = section._sectPr
        bidi = OxmlElement("w:bidi")
        bidi.set(qn("w:val"), "1")
        sectPr.append(bidi)
        pgSz = sectPr.find(qn("w:pgSz"))
        if pgSz is not None:
            pgSz.set(qn("w:orient"), "portrait")

        header = section.header
        header.is_linked_to_previous = False
        hp = header.paragraphs[0]
        hp.clear()
        set_paragraph_rtl(hp, align="center", space_after=2)
        hr = hp.add_run()
        set_run(hr, "شهرداری مشهد  |  سامانه شهرسازی  |  گزارش مدیریتی قانون‌نامه اعتبارسنجی",
                font=HEAD_FONT, size=9, color=NAVY)
        footer = section.footer
        footer.is_linked_to_previous = False
        fp = footer.paragraphs[0]
        fp.clear()
        set_paragraph_rtl(fp, align="center", space_after=0)
        fr = fp.add_run()
        set_run(fr, "سند داخلی — محرمانه سازمانی  ·  ", font=BODY_FONT, size=9, color=GRAY)
        add_page_number(fp)

    # Default style
    normal = doc.styles["Normal"]
    normal.font.name = BODY_FONT
    normal.font.size = Pt(12)
    rPr = normal.element.get_or_add_rPr()
    _rpr_fonts(rPr, BODY_FONT)

    core = doc.core_properties
    core.title = "گزارش مدیریتی قانون‌نامه اعتبارسنجی سامانه شهرسازی مشهد"
    core.author = "تیم مستندسازی اعتبارسنجی شهرسازی"
    core.subject = "خلاصه غیر فنی برای ریاست — بخش‌های ۱ تا ۱۹"
    core.language = "fa-IR"
    core.comments = "بدون تغییر کد زنده سامانه؛ فقط مستندسازی منطق اعتبارسنجی"
    return doc


