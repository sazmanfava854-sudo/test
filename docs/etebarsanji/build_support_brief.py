    add_table(doc, ["پیام / شکایت کارشناس", "معنی واقعی قفل"], tickets)
    if dead:
        add_p(doc, "الان اجرا نمی‌شود (به کارشناس نگویید منتظر همین قفل بماند):",
              size=11.5, bold=True, align="right", space_after=4)
